/** Translate the stored cause without guessing failure from the current screen. */
fun StringSet.description(reason: MissionEndReason): String = when (reason) {
    MissionEndReason.Completed -> lessonSuccessCore
    MissionEndReason.Withdrawal -> lessonWithdrawalCore
    is MissionEndReason.CriticalDepletion -> depletedResources + ": " +
        reason.resources.joinToString { resource ->
            when (resource) {
                CriticalResource.CREW_HEALTH -> crewHealth
                CriticalResource.OXYGEN -> oxygen
                CriticalResource.WATER -> water
                CriticalResource.FOOD -> food
            }
        }
}

/** Use the same destination names in cards, briefings and mission setup. */
