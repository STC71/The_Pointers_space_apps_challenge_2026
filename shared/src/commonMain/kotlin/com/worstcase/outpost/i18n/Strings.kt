/**
 * This object contains every text used in the game.
 * Each text has a version for every language.
 *
 * How to use it:
 *   val text = Strings.get(AppLanguage.SPANISH).appTitle
 */
object Strings {

    /**
     * Returns the correct set of texts for the chosen language.
     * If the language is not found, English is used as fallback.
     */
    fun get(language: AppLanguage): StringSet {
        return when (language) {
            AppLanguage.ENGLISH    -> english
            AppLanguage.SPANISH    -> spanish
            AppLanguage.FRENCH     -> french
            AppLanguage.PORTUGUESE -> portuguese
            AppLanguage.GERMAN     -> german
            AppLanguage.ITALIAN    -> italian
            AppLanguage.JAPANESE   -> japanese
            AppLanguage.KOREAN     -> korean
            AppLanguage.UKRAINIAN  -> ukrainian
            AppLanguage.ARABIC     -> arabic
        }
    }

